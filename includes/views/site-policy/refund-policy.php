            <h2 class="policy-section-title">2. Excepciones a los Reembolsos</h2>
            <p class="policy-text">No se emitirán reembolsos bajo las siguientes circunstancias:</p>
            <ul class="policy-list">
                <li><strong>2.1</strong> Si la solicitud de reembolso se realiza después del período de 14 días desde la transacción original.</li>
                <li><strong>2.2</strong> Para las renovaciones automáticas de suscripciones mensuales o anuales, a menos que el usuario demuestre que intentó cancelar la suscripción antes de la fecha de cobro y por un fallo del sistema no fue posible.</li>
                <li><strong>2.3</strong> Si se determina que el usuario ha violado los Términos y Condiciones, por ejemplo, utilizando la plataforma para fines ilícitos o incurriendo en abuso de las funcionalidades.</li>
                <li><strong>2.4</strong> Si el usuario ha consumido una cuota de uso irrazonablemente alta de los recursos del servidor (ej. múltiples generaciones masivas, excesivo almacenamiento de Snapshots pesados) durante el periodo de 14 días.</li>
            </ul>

            <h2 class="policy-section-title">3. Proceso para Solicitar un Reembolso</h2>
            <p class="policy-text">Para solicitar un reembolso, por favor siga estos pasos:</p>
            <ul class="policy-list">
                <li><strong>3.1</strong> Envíe un correo a <strong>billing@nuestraplataforma.com</strong> desde la dirección de correo electrónico registrada en su cuenta.</li>
                <li><strong>3.2</strong> Incluya en el correo el recibo de pago, número de factura o cualquier información de transacción proporcionada por nuestro proveedor de pagos.</li>
                <li><strong>3.3</strong> Detalle brevemente el motivo de la cancelación. Esto nos ayuda a mejorar nuestros servicios y herramientas de diseño.</li>
            </ul>
            <p class="policy-text">Nuestro equipo revisará su solicitud en un plazo de 3 a 5 días hábiles y le notificará sobre la aprobación o rechazo de su reembolso.</p>

            <h2 class="policy-section-title">4. Tiempos de Procesamiento</h2>
            <p class="policy-text">
                Una vez aprobado, el reembolso será procesado automáticamente al método de pago original utilizado durante la compra. Tenga en cuenta que, dependiendo de su banco o proveedor de tarjeta de crédito, los fondos pueden tardar entre 5 a 10 días hábiles adicionales en reflejarse en su estado de cuenta.
            </p>

            <h2 class="policy-section-title">5. Cancelación de Suscripciones</h2>
            <p class="policy-text">
                Usted puede cancelar la renovación automática de su suscripción Premium en cualquier momento desde la sección de Configuración de Facturación en su perfil. Al cancelar, su plan Premium seguirá activo hasta el final del ciclo de facturación actual, y no se realizarán más cargos a su cuenta. Cancelar una suscripción no implica automáticamente un reembolso de los meses ya pagados o periodos parcialmente utilizados.
            </p>

            <h2 class="policy-section-title">6. Disputas de Pago</h2>
            <p class="policy-text">
